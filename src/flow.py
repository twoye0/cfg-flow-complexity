import torch

from src.velocity import cfg_velocity


def rk4_step(x, t, dt, velocity_fn):
    """
    One Runge-Kutta 4 step for

        dx/dt = v_t(x).
    """

    k1 = velocity_fn(x, t)

    k2 = velocity_fn(
        x + 0.5 * dt * k1,
        t + 0.5 * dt,
    )

    k3 = velocity_fn(
        x + 0.5 * dt * k2,
        t + 0.5 * dt,
    )

    k4 = velocity_fn(
        x + dt * k3,
        t + dt,
    )

    return x + (dt / 6.0) * (
        k1 + 2.0 * k2 + 2.0 * k3 + k4
    )


def integrate_flow(
    x,
    t_start,
    t_end,
    velocity_fn,
    n_steps=200,
):
    """
    Numerically integrate

        dx/dt = v_t(x)

    from t_start to t_end.

    Works in both directions:
        t_start < t_end
        t_start > t_end
    """

    dt = (t_end - t_start) / n_steps

    y = x
    t = float(t_start)

    for _ in range(n_steps):
        y = rk4_step(
            y,
            t,
            dt,
            velocity_fn,
        )
        t += dt

    return y


def cfg_flow(
    x,
    t_start,
    t_end,
    omega,
    c=1,
    sigma=0.5,
    n_steps=200,
):
    """
    Flow map generated by the CFG velocity field.

    Maps a state at t_start to its state at t_end.
    """

    def velocity_fn(y, t):
        return cfg_velocity(
            y,
            t,
            omega=omega,
            c=c,
            sigma=sigma,
        )

    return integrate_flow(
        x,
        t_start=t_start,
        t_end=t_end,
        velocity_fn=velocity_fn,
        n_steps=n_steps,
    )